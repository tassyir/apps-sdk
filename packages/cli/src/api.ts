// A small typed client of the developer API (`developer/*`). Every route,
// its parameters, body and answer are typed from the API's OpenAPI document
// (openapi/openapi.developer.json, vendored from tassyir/backend; the types
// are generated by `npm run openapi:update -w tassyir`), so a call the
// document does not describe does not compile. Two dialects: the sign-in
// routes speak OAuth (form bodies, `{ error, error_description }`), every
// other route JSON with `{ statusCode, code, message, fix, … }` refusals.
// Nothing here prints; `debug` gets method, path and status only, never a
// header or a body.

type HttpMethod = 'get' | 'post' | 'patch' | 'delete';

/** The document's paths that answer `method`. */
type PathsWith<M extends HttpMethod> = {
  [P in keyof paths]: paths[P][M] extends { responses: unknown } ? P : never;
}[keyof paths];

type Operation<M extends HttpMethod, P extends PathsWith<M>> = NonNullable<
  paths[P][M]
>;

type JsonContent<R> = R extends { content: { 'application/json': infer B } }
  ? B
  : never;

/** The JSON body of an operation's success answer. */
type SuccessBody<O> = O extends { responses: infer R }
  ? { [S in keyof R]: S extends 200 | 201 ? JsonContent<R[S]> : never }[keyof R]
  : never;

type PathParams<O> = O extends { parameters: { path: infer X } } ? X : never;
type QueryParams<O> = O extends { parameters: { query?: infer Q } }
  ? NonNullable<Q>
  : never;
type JsonBody<O> = O extends {
  requestBody: { content: { 'application/json': infer B } };
}
  ? B
  : never;
type FormBody<O> = O extends {
  requestBody: {
    content: { 'application/x-www-form-urlencoded': infer B };
  };
}
  ? B
  : never;

/** What a JSON call takes besides its method and path. */
type CallOptions<O> = ([PathParams<O>] extends [never]
  ? { path?: never }
  : { path: PathParams<O> }) &
  ([QueryParams<O>] extends [never]
    ? { query?: never }
    : { query?: QueryParams<O> }) &
  ([JsonBody<O>] extends [never] ? { body?: never } : { body: JsonBody<O> }) & {
    /** This request's timeout, when the client's default is too short. */
    timeoutMs?: number;
    /** Stops the request early (Ctrl-C while following a scan). */
    signal?: AbortSignal;
  };

/** `[options?]` when every option is optional, `[options]` otherwise. */
type CallArgs<O> =
  object extends CallOptions<O>
    ? [options?: CallOptions<O>]
    : [options: CallOptions<O>];

type Answer<M extends HttpMethod, P extends PathsWith<M>> = SuccessBody<
  Operation<M, P>
>;

export type FetchLike = (input: string, init: RequestInit) => Promise<Response>;

/** The CLI's OAuth client id: the only one the API knows today. */
export const CLI_CLIENT_ID = 'tassyir-cli';

export const DEFAULT_API_ORIGIN = 'https://api.tassyir.io';

/** A hosted upload's timeout: its bundle can weigh 4 MB. */
const UPLOAD_TIMEOUT_MS = 120_000;

export interface DeveloperApiOptions {
  /** `https://api.tassyir.io`, or another origin (`TASSYIR_API_ORIGIN`). */
  apiOrigin: string;
  fetch: FetchLike;
  /** `tassyir-cli/<version> …`, so the API's logs can tell CLI calls apart. */
  userAgent: string;
  /** The developer token; absent for the public sign-in routes. */
  token?: string | undefined;
  /** Per request. Default 30 seconds. */
  timeoutMs?: number;
  /** One line per request and answer: method, path, status, duration. */
  debug?: ((line: string) => void) | undefined;
}

/** What `startSignIn` sends: RFC 8628 §3.1 plus the API's optional fields. */
export interface SignInRequest {
  clientVersion?: string | undefined;
  deviceName?: string | undefined;
  locale?: DeviceCodeRequest['locale'] | undefined;
}

/** One poll of `POST /developer/cli/token`. */
export type PollResult =
  | { ok: true; token: DeveloperTokenResponse }
  | {
      ok: false;
      /** An RFC 8628 §3.5 error, or another OAuth error the API sent. */
      error: string;
      description: string | undefined;
      status: number;
      retryAfterSeconds: number | undefined;
    };

/** Codes whose fix the CLI knows better than a generic one, when the API gave none. */
