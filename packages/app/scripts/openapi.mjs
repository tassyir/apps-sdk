// The Admin API's OpenAPI document, vendored from tassyir/backend.
//
//   npm run openapi:check -w @tassyir/app     the vendored file is the backend's (exit 1 when stale)
//   npm run openapi:update -w @tassyir/app    copy the backend's file, record the commit, regenerate
//   npm run openapi:generate -w @tassyir/app  regenerate the types from the vendored file
//
// check and update read the backend clone named by TASSYIR_BACKEND_DIR (read
// only) at `--ref` (default origin/master). Fetch it first.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import * as prettier from 'prettier';
import {
  backendDir,
  refArgument,
  resolveCommit,
  sha256,
  showFile,
} from './backend.mjs';

const PACKAGE = join(dirname(fileURLToPath(import.meta.url)), '..');
const BACKEND_PATH = 'docs/api/apps/openapi.2026-10.json';
const VENDORED = join(PACKAGE, 'openapi', 'openapi.2026-10.json');
const SOURCE = join(PACKAGE, 'openapi', 'SOURCE.json');
const GENERATED = join(PACKAGE, 'src', 'generated', 'admin-api.2026-10.ts');

/** @typedef {{ repository: string, path: string, commit: string, sha256: string }} Source */

/** @returns {Source} */
function readSource() {
  /** @type {unknown} */
  const source = JSON.parse(readFileSync(SOURCE, 'utf8'));
  return /** @type {Source} */ (source);
}

async function generate() {
  const text = readFileSync(VENDORED, 'utf8');
  const source = readSource();
  if (sha256(text) !== source.sha256) {
    throw new Error(
      `${relative(PACKAGE, VENDORED)} does not match the sha256 in ${relative(PACKAGE, SOURCE)}. Fix: run npm run openapi:update -w @tassyir/app instead of editing the file.`,
    );
  }
  const ast = await openapiTS(text);
  const header = [
    `// Generated by \`npm run openapi:generate -w @tassyir/app\` (openapi-typescript)`,
    `// from openapi/openapi.2026-10.json: ${source.repository} ${source.commit},`,
    `// sha256 ${source.sha256}. Do not edit by hand.`,
    '',
  ].join('\n');
  const config = (await prettier.resolveConfig(GENERATED)) ?? {};
  const output = await prettier.format(`${header}\n${astToString(ast)}`, {
    ...config,
    filepath: GENERATED,
  });
  writeFileSync(GENERATED, output);
  console.log(`✓ wrote ${relative(PACKAGE, GENERATED)}`);
}

function check() {
  const dir = backendDir();
  const ref = refArgument(process.argv);
  const source = readSource();
  const vendored = readFileSync(VENDORED, 'utf8');
  const problems = [];
  if (sha256(vendored) !== source.sha256) {
    problems.push(
      `${relative(PACKAGE, VENDORED)} was edited: its sha256 is not the one recorded in SOURCE.json.`,
    );
  }
  if (showFile(dir, source.commit, BACKEND_PATH) !== vendored) {
    problems.push(
      `${relative(PACKAGE, VENDORED)} is not the backend's file at the recorded commit ${source.commit}.`,
    );
  }
  const commit = resolveCommit(dir, ref);
  if (showFile(dir, commit, BACKEND_PATH) !== vendored) {
    problems.push(
      `The backend's ${BACKEND_PATH} changed: ${ref} (${commit.slice(0, 12)}) differs from the vendored copy of ${source.commit.slice(0, 12)}.`,
    );
  }
  if (problems.length > 0) {
    console.error(
      `${problems.map((p) => `✗ ${p}`).join('\n')}\n  Fix: npm run openapi:update -w @tassyir/app, review the type changes, add a changeset.`,
    );
    process.exit(1);
  }
  console.log(
    `✓ openapi.2026-10.json is the backend's at ${ref} (${commit.slice(0, 12)})`,
  );
}

async function update() {
  const dir = backendDir();
  const ref = refArgument(process.argv);
  const commit = resolveCommit(dir, ref);
  const text = showFile(dir, commit, BACKEND_PATH);
  JSON.parse(text);
  writeFileSync(VENDORED, text);
  /** @type {Source} */
  const source = {
    repository: 'tassyir/backend',
    path: BACKEND_PATH,
    commit,
    sha256: sha256(text),
  };
  writeFileSync(SOURCE, `${JSON.stringify(source, null, 2)}\n`);
  console.log(`✓ vendored ${BACKEND_PATH} at ${commit.slice(0, 12)} (${ref})`);
  await generate();
}

const command = process.argv[2];
if (command === 'check') check();
else if (command === 'update') await update();
else if (command === 'generate') await generate();
else {
  console.error(
    'Usage: node scripts/openapi.mjs check|update|generate [--ref <git ref>]',
  );
  process.exit(2);
}
